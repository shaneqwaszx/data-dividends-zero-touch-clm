import { useEffect, useState, type FormEvent } from "react";

import { ApiError, createAdminTeam, fetchAdminTeams, updateAdminTeam } from "../api";
import type { AdminTeam } from "../types";

export default function AdminTeams() {
  const [teams, setTeams] = useState<AdminTeam[]>([]);
  const [displayName, setDisplayName] = useState("");
  const [scope, setScope] = useState("");
  const [description, setDescription] = useState("");
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    void fetchAdminTeams().then(setTeams).catch((reason) => setError(reason instanceof ApiError ? reason.message : "Teams are unavailable."));
  }, []);

  async function create(event: FormEvent) {
    event.preventDefault();
    try {
      const created = await createAdminTeam({ display_name: displayName, client_scope_label: scope, ...(description ? { description } : {}) });
      setTeams((current) => [...current, created]);
      setDisplayName(""); setScope(""); setDescription(""); setError(null);
    } catch (reason) {
      setError(reason instanceof ApiError ? reason.message : "Team creation failed.");
    }
  }

  async function edit(team: AdminTeam) {
    const nextName = globalThis.prompt("Team display name", team.display_name)?.trim();
    if (!nextName) return;
    const nextScope = globalThis.prompt("Client scope label", team.client_scope_label)?.trim();
    if (!nextScope) return;
    const nextDescription = globalThis.prompt("Description", team.description)?.trim() ?? team.description;
    try {
      const changed = await updateAdminTeam(team.team_id, {
        expected_version: team.version,
        display_name: nextName,
        client_scope_label: nextScope,
        description: nextDescription || null,
      });
      setTeams((current) => current.map((item) => item.team_id === changed.team_id ? changed : item));
      setError(null);
    } catch (reason) {
      if (reason instanceof ApiError && reason.status === 409) {
        setTeams(await fetchAdminTeams());
      }
      setError(reason instanceof ApiError ? reason.message : "Team update failed.");
    }
  }

  return <div className="ds-root ds-page">
    <h1>Teams</h1><p className="text-muted">Canonical active onboarding teams. IDs are generated by the server and remain stable.</p>
    {error && <div className="ds-banner ds-banner-warn">{error}</div>}
    <form className="card form-stack" onSubmit={(event) => void create(event)}>
      <h3>Create team</h3>
      <label>Display name<input value={displayName} minLength={2} maxLength={80} required onChange={(event) => setDisplayName(event.target.value)} /></label>
      <label>Client scope label<input value={scope} minLength={2} maxLength={80} required onChange={(event) => setScope(event.target.value)} /></label>
      <label>Description<input value={description} maxLength={240} onChange={(event) => setDescription(event.target.value)} /></label>
      <button type="submit" className="btn btn-primary">Create team</button>
    </form>
    <div className="table-card table-scroll" tabIndex={0}><table className="table"><thead><tr><th>Team</th><th>Scope</th><th>Type</th><th>Version</th><th>Action</th></tr></thead><tbody>
      {teams.map((team) => <tr key={team.team_id}><td><strong>{team.display_name}</strong><div className="text-muted">{team.team_id}</div></td><td>{team.client_scope_label}</td><td>{team.team_type}</td><td>{team.version}</td><td><button type="button" className="btn btn-ghost" onClick={() => void edit(team)}>Edit</button></td></tr>)}
    </tbody></table></div>
  </div>;
}
