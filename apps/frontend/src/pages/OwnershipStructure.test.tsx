// @vitest-environment jsdom
import { act } from "react";
import { createRoot, type Root } from "react-dom/client";
import { afterEach, describe, expect, it, vi } from "vitest";
import type { OwnershipAnalysisRecord } from "../types";
import OwnershipPathExplorer from "./OwnershipPathExplorer";
import { ownershipStructureFixture } from "./ownershipStructureFixture";
import validSourceRecord from "./ownershipValidIdentityFixture.json";

(globalThis as typeof globalThis & { IS_REACT_ACT_ENVIRONMENT: boolean }).IS_REACT_ACT_ENVIRONMENT = true;
let root: Root; let host: HTMLDivElement;
afterEach(() => { act(() => root.unmount()); host.remove(); vi.restoreAllMocks(); });
function render(record = ownershipStructureFixture()) { host = document.createElement("div"); document.body.append(host); root = createRoot(host); act(() => root.render(<OwnershipPathExplorer record={record} />)); return host; }
function button(name: string) { return [...host.querySelectorAll<HTMLButtonElement>("button")].find(b => (b.getAttribute("aria-label") ?? b.textContent) === name)!; }
function validIdentityRecord(relationshipId = "root") {
  // Canonical API evidence generated by the independently validated Mock source/Decimal probe.
  const record = structuredClone(validSourceRecord) as unknown as OwnershipAnalysisRecord;
  record.relationships[0].relationship_id = relationshipId;
  for (const candidate of record.candidates) for (const path of candidate.paths) {
    for (const edge of path.edges) if (edge.relationship_id === "root") edge.relationship_id = relationshipId;
  }
  return record;
}

describe("Ownership hierarchy and authoritative candidate summary", () => {
  it.each(["root", "client:root", "unlinked:avery", "path.root-1", "A:B_C.D-1"])(
    "selects the actual retained holder with valid relationship ID %s without duplicate keys",
    (relationshipId) => {
      const errors = vi.spyOn(console, "error").mockImplementation(() => undefined);
      const record = validIdentityRecord(relationshipId);
      const candidate = record.candidates.find(item => item.party.display_name === "Avery Tan")!;
      render(record);
      act(() => button("Avery Tan").click());
      const detail = host.querySelector('[aria-label="Selected holder"]')!;
      expect(detail.querySelector("h5")!.textContent).toBe("Avery Tan");
      expect(detail.textContent).toContain("60%");
      expect(detail.textContent).toContain("PROVISIONAL_UBO_CANDIDATE");
      expect(candidate.threshold_result).toBe("MET");
      expect(errors.mock.calls.filter(args => args.some(value => String(value).includes("same key")))).toEqual([]);
    },
  );
  it("retains root and unlinked selection across a current-analysis refresh", () => {
    const record = validIdentityRecord();
    record.parties.push({ ...record.parties[0], party_id: "unlinked:root", display_name: "Unlinked holder" });
    render(record);
    act(() => button("Avery Tan").click());
    act(() => button(record.parties.find(party => party.party_id === record.root_party_id)!.display_name).click());
    act(() => root.render(<OwnershipPathExplorer record={structuredClone(record)} />));
    expect(host.querySelector('[aria-label="Selected holder"] h5')!.textContent).toBe(record.parties[0].display_name);
    act(() => button("Unlinked holder").click());
    act(() => root.render(<OwnershipPathExplorer record={structuredClone(record)} />));
    expect(host.querySelector('[aria-label="Selected holder"] h5')!.textContent).toBe("Unlinked holder");
    expect(host.querySelector('[aria-label="Selected holder"]')!.textContent).toContain("No retained root path");
  });
  it("keeps repeated-holder occurrences and collapse independent, then reconciles removed paths", () => {
    const record = ownershipStructureFixture();
    const oldId = record.relationships[0].relationship_id;
    record.relationships[0].relationship_id = "root";
    for (const candidate of record.candidates) for (const path of candidate.paths) {
      for (const edge of path.edges) if (edge.relationship_id === oldId) edge.relationship_id = "root";
    }
    render(record);
    const occurrences = [...host.querySelectorAll<HTMLButtonElement>('[aria-label="Ownership hierarchy"] button')]
      .filter(control => control.textContent === "Synthetic qualifying person");
    expect(occurrences).toHaveLength(2);
    act(() => occurrences[1].click());
    const chosen = host.querySelector('[aria-label="Selected holder"]')!.textContent;
    act(() => button("Collapse holders of Synthetic holding").click());
    act(() => occurrences[1].click());
    act(() => root.render(<OwnershipPathExplorer record={structuredClone(record)} />));
    expect(button("Expand holders of Synthetic holding").getAttribute("aria-expanded")).toBe("false");
    expect(host.querySelector('[aria-label="Selected holder"]')!.textContent).toBe(chosen);
    const refreshed = structuredClone(record);
    refreshed.relationships = refreshed.relationships.filter(edge => edge.child_party_id !== "person");
    refreshed.candidates = [];
    refreshed.parties = refreshed.parties.filter(party => party.party_id !== "person");
    act(() => root.render(<OwnershipPathExplorer record={refreshed} />));
    expect(host.querySelector('[aria-label="Selected holder"] h5')!.textContent).not.toBe("Synthetic qualifying person");
    const replacement = validIdentityRecord(); replacement.analysis_id = "replacement-analysis";
    act(() => root.render(<OwnershipPathExplorer record={replacement} />));
    expect(host.querySelector('[aria-label="Selected holder"] h5')!.textContent).toBe("Avery Tan");
  });
  it("shows three levels, repeated holders, rounded path values, zero and unknown distinctly", () => {
    const view = render(); const hierarchy = view.querySelector('[aria-label="Ownership hierarchy"]')!;
    expect(hierarchy.querySelectorAll('[role="row"]')).toHaveLength(6);
    expect(hierarchy.textContent).toContain("<0.01%");
    expect(hierarchy.textContent).toContain("25%"); expect(hierarchy.textContent).toContain("0%");
    expect(hierarchy.textContent).toContain("Not retained"); expect(hierarchy.textContent).toContain("Not supplied");
    expect(hierarchy.textContent).toContain("LOCAL_SYNTHETIC_SUPPLEMENT · LOCAL");
    const summary = view.querySelector(".ubo-summary")!;
    expect(summary.querySelectorAll("li")).toHaveLength(1);
    expect(summary.textContent).toContain("25% effective");
    expect(summary.textContent).not.toContain("Synthetic below-threshold person");
    expect(summary.querySelector("li > strong")!.textContent).toBe("Synthetic qualifying person");
  });
  it("keeps a below-threshold person excluded even when its rounded label equals the threshold", () => {
    const record = ownershipStructureFixture();
    record.candidates[1].aggregated_ownership_percent = "24.999999999999999999";
    record.candidates[1].direct_ownership_percent = "24.999999999999999999";
    const original = structuredClone(record); const view = render(record);
    act(() => button("Synthetic below-threshold person").click());
    expect(view.querySelector('[aria-label="Selected holder"]')!.textContent).toContain("25%");
    expect(view.querySelector('[aria-label="Selected holder"]')!.textContent).toContain("NOT_MET");
    expect(view.querySelector(".ubo-summary")!.textContent).not.toContain("Synthetic below-threshold person");
    expect(view.querySelector(".ubo-summary li")).not.toBeNull(); expect(record).toEqual(original);
  });
  it("allows native keyboard controls, collapse/expand, holder selection and distinct path inspection", () => {
    render(); const collapse = button("Collapse holders of Synthetic holding");
    collapse.focus(); expect(document.activeElement).toBe(collapse); act(() => collapse.click());
    expect(button("Expand holders of Synthetic holding").getAttribute("aria-expanded")).toBe("false");
    expect(host.querySelector('[aria-label="Ownership hierarchy"]')!.querySelectorAll('[role="row"]')).toHaveLength(5);
    act(() => button("Expand holders of Synthetic holding").click());
    act(() => button("Synthetic qualifying person").click());
    expect(host.querySelector('[aria-label="Selected holder"]')!.textContent).toContain("50 × 50 / 100 = 25");
    act(() => button("Inspect direct").click());
    expect(host.textContent).toContain("Selected retained path: direct");
  });
  it("stops cycles and labels unlinked parties without turning incomplete evidence into no UBOs", () => {
    const record = ownershipStructureFixture(); record.state = "REVIEW_REQUIRED";
    record.candidates[0].classification = "INDETERMINATE"; record.candidates[0].threshold_result = "INDETERMINATE";
    record.relationships.push({ ...record.relationships[0], relationship_id: "cycle", parent_party_id: "holding", child_party_id: "root" });
    record.parties.push({ ...record.parties[0], party_id: "unlinked", display_name: "Unlinked entity" });
    const view = render(record);
    expect(view.textContent).toContain("Cycle — traversal stopped"); expect(view.textContent).toContain("No retained root path");
    expect(view.textContent).toContain("UBO determination requires review");
    expect(view.querySelector(".ubo-summary li")).toBeNull();
  });
});

describe("Ownership hierarchy rows and summary header", () => {
  it("marks the client, the owned entity and provisional UBO rows, and keeps the selected holder highlighted", () => {
    const record = validIdentityRecord();
    render(record);
    const rows = [...host.querySelectorAll<HTMLElement>('[aria-label="Ownership hierarchy"] [role="row"]:not(.ownership-structure__head)')];
    expect(rows[0].classList.contains("is-client")).toBe(true);
    expect(rows[0].textContent).toContain("Client");
    const avery = rows.find(row => row.textContent?.includes("Avery Tan"))!;
    expect(avery.textContent).toContain("Holds 60% of");
    expect(avery.textContent).toContain("Provisional UBO");
    act(() => button("Avery Tan").click());
    expect(host.querySelector('[aria-label="Ownership hierarchy"] [role="row"].is-selected')!.textContent).toContain("Avery Tan");
    expect(host.querySelector('[aria-label="Ownership hierarchy"] .ownership-node__body > button[aria-pressed="true"]')!.textContent).toBe("Avery Tan");
    const stats = host.querySelector('[aria-label="Hierarchy summary"]')!;
    expect(stats.textContent).toContain(`${record.parties.length} part`);
    expect(stats.textContent).toContain("provisional UBO");
  });
});
